def test_the_client_dependency_names_a_public_https_commit() -> None:
    """A floating @main makes every client merge a silent break, and git+ssh breaks
    unauthenticated installs and CI."""
    config = (HERE / "pyproject.toml").read_text(encoding="utf-8")
    match = re.search(r'"zmk-studio-client @ (\S+)"', config)
    assert match, "the client dependency is no longer spelled as a single git URL"
    url = match.group(1)
    assert url.startswith("git+https://github.com/asimkprasad/zmk-studio-client.git@"), (
        f"client URL must use public HTTPS, got {url!r}"
    )
    reference = url.rsplit("@", 1)[1]
    assert re.fullmatch(r"[0-9a-f]{40}", reference), (
        f"zmk-studio-client is pinned to {reference!r}; it must name a full commit "
        f"sha, so that updating the library is a commit in this repository")
