"""What the package promises about its dependencies and metadata, checked against the code.

protoc writes the compiler version into every file it generates and the generated
module validates it at import time, so the declared floor is not a judgement call -
it is readable from the bindings. A regeneration that moves the gencode version
without moving the floor produces a package that cannot import on the version it
claims to support, and a lockfile resolving something newer hides it completely.
"""
from __future__ import annotations

import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parents[1]


def _version(text: str) -> tuple[int, ...]:
    return tuple(int(part) for part in text.split("."))


def gencode_versions() -> dict[str, tuple[int, ...]]:
    """The protobuf version recorded in each generated module."""
    found = {}
    for path in sorted((HERE / "src" / "zmk_keymap" / "proto").glob("*_pb2.py")):
        match = re.search(
            r"# Protobuf Python Version: ([\d.]+)",
            path.read_text(encoding="utf-8"),
        )
        assert match, f"{path.name} does not record its gencode version"
        found[path.name] = _version(match.group(1))
    assert found, "no generated *_pb2.py modules found under src/zmk_keymap/proto/"
    return found


def declared_floor() -> tuple[int, ...]:
    """The protobuf lower bound in pyproject.toml."""
    text = (HERE / "pyproject.toml").read_text(encoding="utf-8")
    match = re.search(r'"protobuf>=([\d.]+)', text)
    assert match, "pyproject.toml declares no protobuf floor"
    return _version(match.group(1))


def test_the_declared_floor_is_not_below_the_generated_code() -> None:
    floor = declared_floor()
    for name, gencode in gencode_versions().items():
        assert gencode <= floor, (
            f"{name} was generated by protobuf {gencode} but pyproject.toml allows "
            f"{floor}. Importing the package on the declared floor would raise "
            f"VersionError from ValidateProtobufRuntimeVersion."
        )


def test_the_floor_is_capped_below_the_next_major() -> None:
    """protobuf rejects gencode from a different major version in both directions."""
    text = (HERE / "pyproject.toml").read_text(encoding="utf-8")
    match = re.search(r'"protobuf>=[\d.]+,<(\d+)"', text)
    assert match, "protobuf has no upper bound; a new major will reject this gencode"
    assert int(match.group(1)) == declared_floor()[0] + 1


def test_every_generated_module_agrees_on_the_compiler() -> None:
    """A mixed set means someone regenerated part of proto/ with a different protoc."""
    assert len(set(gencode_versions().values())) == 1, gencode_versions()


def test_nothing_reaches_above_this_repository() -> None:
    """No source or test module may walk above the repository root via `parents[...]`.

    A module under `src/zmk_keymap/` sits two levels below the repository root (three
    for `src/zmk_keymap/proto/`), and `tests/` sits one level below. Checking both
    trees - and asserting both are non-empty so a renamed directory cannot make the
    scan silently vacuous - guarantees nothing reaches outside the checkout.
    """
    src_files = sorted((HERE / "src").rglob("*.py"))
    test_files = sorted((HERE / "tests").rglob("*.py"))
    assert src_files, "src/ yielded no Python files; directory layout changed"
    assert test_files, "tests/ yielded no Python files"

    offenders = []
    for path in (*src_files, *test_files):
        # How many .parents[...] hops reach HERE from `path` (`parents[0]` is `path.parent`).
        max_inside = len(path.relative_to(HERE).parts) - 1
        for depth in re.findall(r"\.parents\[(\d+)\]", path.read_text(encoding="utf-8")):
            if int(depth) > max_inside:
                offenders.append(f"{path.relative_to(HERE)}: parents[{depth}]")
    assert not offenders, (
        "these reach outside the repository root: " + ", ".join(offenders)
    )


def test_a_snapshot_records_the_version_of_the_tool_that_wrote_it() -> None:
    """A rename used to turn this into "unknown" with no error anywhere."""
    from zmk_keymap.snapshot import _tool_version

    assert _tool_version() != "unknown", (
        "the installed package cannot find its own version; _tool_version() is "
        "looking up a distribution name that does not match this package")
    assert _tool_version() == declared_version()


def declared_version() -> str:
    """The version in pyproject.toml, which is what metadata should report."""
    text = (HERE / "pyproject.toml").read_text(encoding="utf-8")
    match = re.search(r'^version = "([^"]+)"', text, re.M)
    assert match, "pyproject.toml declares no version"
    return match.group(1)


def test_licence_metadata_and_files_agree() -> None:
    """pyproject.toml, LICENSE, and README.md must state the same licence."""
    pyproject = (HERE / "pyproject.toml").read_text(encoding="utf-8")
    assert 'license = "MIT"' in pyproject
    license_file = HERE / "LICENSE"
    assert license_file.is_file(), "LICENSE file is missing"
    assert "MIT License" in license_file.read_text(encoding="utf-8")
    readme = (HERE / "README.md").read_text(encoding="utf-8")
    assert "TBD" not in readme
    assert "MIT" in readme


